"""Launch-region details: emergency numbers and the fixed safety messages.

The messages live in fixed_messages.json, one set per region and language.
They are human-written text, never generated by a model. Every language
other than English is a DRAFT until a native-speaking clinician signs it off
(see the testing plan); until then a missing language falls back to English.

India is the launch region. Set CARECHAT_REGION=US to switch.
Numbers must be re-checked with official sources before launch.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path

_MESSAGES = json.loads((Path(__file__).parent / "fixed_messages.json").read_text(encoding="utf-8"))

MESSAGE_KINDS = ("emergency", "self_harm", "unavailable", "critical_value", "disclaimer")


@dataclass(frozen=True)
class Region:
    code: str
    emergency_number: str  # general emergency line
    ambulance_number: str
    crisis_number: str  # mental health crisis line
    crisis_line_name: str
    texts: dict[str, dict[str, str]] = field(default_factory=dict)

    def text(self, kind: str, language: str | None = None) -> str:
        lang = self.texts.get(language or "en") or {}
        return lang.get(kind) or self.texts["en"][kind]

    def messages(self, language: str | None) -> tuple[str, str, str]:
        return (self.text("emergency", language), self.text("self_harm", language), self.text("unavailable", language))

    @property
    def emergency_message(self) -> str:
        return self.text("emergency")

    @property
    def self_harm_message(self) -> str:
        return self.text("self_harm")

    @property
    def unavailable_message(self) -> str:
        return self.text("unavailable")

    @property
    def disclaimer(self) -> str:
        return self.text("disclaimer")

    def reviewed_languages(self) -> list[str]:
        return sorted(self.texts)


INDIA = Region(
    code="IN", emergency_number="112", ambulance_number="108", crisis_number="14416",
    crisis_line_name="Tele-MANAS", texts=_MESSAGES["IN"],
)

US = Region(
    code="US", emergency_number="911", ambulance_number="911", crisis_number="988",
    crisis_line_name="988 Suicide & Crisis Lifeline", texts=_MESSAGES["US"],
)

REGIONS = {r.code: r for r in (INDIA, US)}


def get_region(code: str) -> Region:
    try:
        return REGIONS[code.upper()]
    except KeyError:
        raise ValueError(f"Unknown CARECHAT_REGION {code!r}; use one of {sorted(REGIONS)}") from None
