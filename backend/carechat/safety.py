"""Emergency and self-harm screening that runs before every answer.

Two layers:
1. A keyword check that catches clear emergency phrases with no model call.
2. A fast classifier (Claude Haiku) for everything the keywords miss.

If the classifier can't run, the request fails closed: the user gets a
fixed message telling them how to get help, never an unscreened answer.
"""

from __future__ import annotations

import logging
import re
from enum import Enum
from typing import Literal

import anthropic
from pydantic import BaseModel

from .config import settings
from .llm import get_client
from .region import get_region

log = logging.getLogger(__name__)


class Verdict(str, Enum):
    OK = "ok"
    EMERGENCY = "emergency"
    SELF_HARM = "self_harm"
    UNAVAILABLE = "unavailable"


# Fixed, human-written messages for the launch region. Never generated by a model.
REGION = get_region(settings.region_code)

FIXED_MESSAGES = {
    Verdict.EMERGENCY: REGION.emergency_message,
    Verdict.SELF_HARM: REGION.self_harm_message,
    Verdict.UNAVAILABLE: REGION.unavailable_message,
}

_SELF_HARM_PATTERNS = [
    r"\bsuicid",
    r"\bkill(ing)? myself\b",
    r"\bend(ing)? (it all|my life)\b",
    r"\bwant to die\b",
    r"\bhurt(ing)? myself\b",
    r"\bself[- ]harm",
    r"\bno reason to live\b",
]

_EMERGENCY_PATTERNS = [
    r"\bchest (pain|pressure|tightness)\b",
    r"\b(can'?t|cannot|can not|hard to|trouble|difficulty) breath",
    r"\bnot breathing\b",
    r"\bshort(ness)? of breath\b",
    r"\bface (is )?droop",
    r"\bslurred speech\b",
    r"\b(arm|leg|side of (my|his|her|their) body) (went|is|feels) (numb|weak)\b",
    r"\b(having|had) a (stroke|heart attack)\b",
    r"\b(having|had) a seizure\b(?! disorder)",
    r"\bseizing\b",
    r"\b(passed out|unconscious|unresponsive|won'?t wake up)\b",
    r"\boverdos",
    r"\b(severe|heavy|uncontrolled) bleeding\b",
    r"\bbleeding (won'?t|will not|doesn'?t) stop\b",
    r"\b(coughing|vomiting|throwing) up blood\b",
    r"\banaphyla",
    r"\bthroat (is )?(closing|swelling)\b",
    r"\bworst headache\b",
]

_SELF_HARM_RE = re.compile("|".join(_SELF_HARM_PATTERNS), re.IGNORECASE)
_EMERGENCY_RE = re.compile("|".join(_EMERGENCY_PATTERNS), re.IGNORECASE)


def keyword_check(text: str) -> Verdict:
    """Deterministic first pass. Self-harm wins over other emergencies."""
    if _SELF_HARM_RE.search(text):
        return Verdict.SELF_HARM
    if _EMERGENCY_RE.search(text):
        return Verdict.EMERGENCY
    return Verdict.OK


CLASSIFIER_SYSTEM = """You screen messages sent to a patient education chat app for safety.
Classify the user's latest message, using the earlier messages only as context.

- "self_harm": any sign the user may hurt or kill themselves, or is in crisis.
- "emergency": the user, or someone with them, may have an emergency now or very soon. Examples: \
chest pain, trouble breathing, stroke signs, severe bleeding, fainting, seizure, severe allergic \
reaction, poisoning or overdose, a very high fever in a baby, sudden severe pain, or a lab value \
the user says their doctor or lab called urgent.
- "ok": anything else, including general questions about these topics with no sign that \
someone is affected right now (for example "what is a stroke?").

Messages may be in English, Hindi, Hinglish or another Indian language. Judge the meaning, not the language.

When unsure between "ok" and another label, choose the other label."""


class _Classification(BaseModel):
    label: Literal["ok", "emergency", "self_harm"]


async def classify(user_messages: list[str]) -> Verdict:
    """Model-based check of the latest user message. Fails closed."""
    if not user_messages:
        return Verdict.OK
    context = user_messages[-3:]
    transcript = "\n".join(
        f"<earlier_message>{m}</earlier_message>" for m in context[:-1]
    ) + f"\n<latest_message>{context[-1]}</latest_message>"
    try:
        response = await get_client().messages.parse(
            model=settings.safety_model,
            max_tokens=2048,
            system=CLASSIFIER_SYSTEM,
            output_config={"effort": "low"},
            messages=[{"role": "user", "content": transcript.strip()}],
            output_format=_Classification,
        )
    except anthropic.APIError:
        log.exception("Safety classifier call failed")
        return Verdict.UNAVAILABLE
    if response.stop_reason == "refusal":
        log.warning("Safety classifier declined the request")
        return Verdict.UNAVAILABLE
    parsed = response.parsed_output
    if parsed is None:
        log.error("Safety classifier returned no parsed output (stop_reason=%s)", response.stop_reason)
        return Verdict.UNAVAILABLE
    return Verdict(parsed.label)


async def screen(user_messages: list[str]) -> Verdict:
    """Run both layers on the conversation's user messages."""
    if not user_messages:
        return Verdict.OK
    quick = keyword_check(user_messages[-1])
    if quick is not Verdict.OK:
        return quick
    return await classify(user_messages)
